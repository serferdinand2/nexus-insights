const { app, BrowserWindow, Menu, Tray, ipcMain, shell } = require('electron');
const path = require('path');
const fs   = require('fs');

const { initDatabase } = require('./services/database');
const { loadConfig, setConfigValue } = require('./services/config');
const { createUpdater } = require('./services/updater');

// No application menu — the File/Edit/View/Window/Help bar is Electron's
// default, not something this app uses. Removing it also removes its
// accelerators, so the useful ones are re-bound below.
Menu.setApplicationMenu(null);

// Only one copy may run. Without this, launching from the desktop shortcut
// while the tray copy is already running would open a second window — and two
// processes writing the same SQLite file is asking for trouble.
const gotTheLock = app.requestSingleInstanceLock();
if (!gotTheLock) {
  app.quit();
}

let tray       = null;
let mainWindow = null;
// Distinguishes "user pressed X" (may mean hide) from "user chose Quit"
// (always means quit). Without it, Quit from the tray would just hide again.
let isQuitting = false;

const ICON_PATH = path.join(__dirname, 'assets', 'icon.ico');

/**
 * Reflect the startOnLogin setting into the OS.
 *
 * `openAsHidden` keeps the login launch from stealing focus — the app starts
 * straight into the tray and quietly begins watching LP, which is the whole
 * point of starting it automatically.
 */
// Name of the shim dropped into the Windows Startup folder when running from
// source. Kept as a constant so enabling and disabling can't drift apart.
const STARTUP_SHIM = 'Nexus Insights.vbs';

// Registry value name used by the installed build's "Start with Windows".
// Must match the DeleteRegValue in installer/installer.nsh.
const LOGIN_ITEM_NAME = 'Nexus Insights';

function startupFolderPath() {
  return path.join(
    process.env.APPDATA || '',
    'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup'
  );
}

/**
 * Build the Startup shim — the same trick as the desktop launcher: run
 * electron.cmd with window style 0 so no console flashes up at login.
 *
 * The app directory is passed as "." with the working directory set to it,
 * which avoids any quoting trouble from the space in "Nexus Insights".
 */
function startupShimSource(appDir) {
  const electronCmd = path.join(appDir, 'node_modules', '.bin', 'electron.cmd');
  return [
    // Kept strictly ASCII: this is written as latin1 for VBScript, which
    // would mangle characters like an em-dash.
    "' Auto-generated by Nexus Insights - starts the app hidden at login.",
    "' Delete this file, or untick \"Start with Windows\" in Settings, to stop it.",
    '',
    'Option Explicit',
    'Dim shell, fso',
    'Set shell = CreateObject("WScript.Shell")',
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    '',
    `If Not fso.FileExists("${electronCmd}") Then WScript.Quit 1`,
    '',
    `shell.CurrentDirectory = "${appDir}"`,
    `shell.Run """${electronCmd}"" . --hidden", 0, False`,
    ''
  ].join('\r\n');
}

/**
 * Reflect the startOnLogin setting into the OS.
 *
 * Two different mechanisms, because they have different failure modes:
 *
 *  - Packaged build: app.setLoginItemSettings registers the app's own
 *    executable, which already knows where its app lives. Works cleanly.
 *
 *  - Running from source (this setup): the executable is Electron itself, so a
 *    registry entry has to carry the app directory too. That proved brittle —
 *    an entry missing the path launches a bare Electron, which shows its
 *    default "run a local app" welcome screen. Instead a .vbs shim goes in the
 *    Startup folder, mirroring the desktop launcher that already works. It is
 *    a plain file, so it can be inspected, edited or deleted by hand, and any
 *    stale Run-key entry is actively cleared.
 */
function applyLoginItemSetting(enabled) {
  if (process.platform === 'linux') return; // no supported API

  try {
    if (process.platform !== 'win32' || app.isPackaged) {
      app.setLoginItemSettings({
        openAtLogin:  !!enabled,
        openAsHidden: !!enabled,
        args: enabled ? ['--hidden'] : [],
        // Fixed registry value name (HKCU\...\Run). Without it Electron uses
        // the AppUserModelId, which isn't predictable — and the uninstaller
        // (installer/installer.nsh) needs to know the exact name to remove
        // the entry, or Windows keeps trying to launch a deleted program.
        name: LOGIN_ITEM_NAME
      });
      return;
    }

    // --- Windows, running from source ---

    // Clear any legacy Run-key entry from the earlier approach. Without this,
    // the broken bare-Electron entry keeps firing at login alongside the shim.
    try {
      app.setLoginItemSettings({ openAtLogin: false });
    } catch (e) {
      console.warn('Could not clear legacy Run entry:', e.message);
    }

    const folder = startupFolderPath();
    const shim   = path.join(folder, STARTUP_SHIM);

    if (!enabled) {
      if (fs.existsSync(shim)) {
        fs.unlinkSync(shim);
        console.log('Removed startup shim:', shim);
      }
      return;
    }

    if (!fs.existsSync(folder)) {
      console.warn('Startup folder not found, cannot enable autostart:', folder);
      return;
    }

    fs.writeFileSync(shim, startupShimSource(app.getAppPath()), 'latin1');
    console.log('Startup shim written:', shim);
  } catch (err) {
    console.warn('Could not update login item settings:', err.message);
  }
}

function showMainWindow() {
  if (!mainWindow) return;
  if (mainWindow.isMinimized()) mainWindow.restore();
  mainWindow.show();
  mainWindow.focus();
}

function createTray() {
  if (tray) return;
  try {
    tray = new Tray(ICON_PATH);
  } catch (err) {
    console.warn('Tray icon could not be created:', err.message);
    return;
  }

  const menu = Menu.buildFromTemplate([
    { label: 'Open Nexus Insights', click: showMainWindow },
    { type: 'separator' },
    {
      label: 'Quit',
      click: () => {
        isQuitting = true;
        app.quit();
      }
    }
  ]);

  tray.setToolTip('Nexus Insights — watching LP');
  tray.setContextMenu(menu);
  tray.on('double-click', showMainWindow);
}

function createWindow() {
  const win = new BrowserWindow({
    width: 1400,
    height: 900,
    minWidth: 1024,
    minHeight: 700,
    // Content tops out around ~1000px tall (Overview tab, calendar + charts
    // + footer). Without a cap, maximizing on a tall monitor left a growing
    // blank gap below the footer since nothing in the page fills that space.
    maxHeight: 1100,

    // Taskbar / alt-tab icon. Frameless windows have no title bar to show it,
    // but Windows still uses it everywhere else.
    icon: path.join(__dirname, 'assets', 'icon.ico'),

    // Frameless: the OS title bar is replaced by the in-app header, which
    // carries the drag region and the minimise/maximise/close buttons.
    frame: false,

    // Painting the window this colour up front avoids the white flash
    // between the window appearing and the first render.
    backgroundColor: '#0b0d13',
    show: false,

    webPreferences: {
      nodeIntegration: true,
      contextIsolation: false,

      // Chromium throttles timers in hidden or occluded windows — a background
      // page can be cut to roughly one tick a minute. The LP watcher is a
      // setInterval in this renderer and it matters most precisely when the
      // window is hidden in the tray, so the throttling has to be off or the
      // whole close-to-tray feature is decorative.
      backgroundThrottling: false
    }
  });

  win.loadFile(path.join(__dirname, 'index.html'));

  // Web links belong in the user's browser, never inside the app window
  // (which has Node access). Covers target=_blank and plain link clicks.
  const openOutside = (url) => {
    if (/^https:\/\//i.test(url)) shell.openExternal(url);
  };
  win.webContents.setWindowOpenHandler(({ url }) => { openOutside(url); return { action: 'deny' }; });
  win.webContents.on('will-navigate', (event, url) => {
    if (!url.startsWith('file:')) { event.preventDefault(); openOutside(url); }
  });

  // Launched by Windows at login? Start straight into the tray rather than
  // popping a window in front of whatever the user is doing.
  const startHidden = process.argv.includes('--hidden') ||
                      app.getLoginItemSettings().wasOpenedAsHidden;

  // Show only once there's something to show
  win.once('ready-to-show', () => { if (!startHidden) win.show(); });

  // X hides to the tray when the setting is on. The renderer keeps polling LP
  // while hidden — that's the reason the option exists.
  win.on('close', (event) => {
    if (isQuitting) return;
    const { closeToTray } = loadConfig();
    if (!closeToTray) return;

    event.preventDefault();
    win.hide();
  });

  // Keep the renderer's maximise/restore icon in sync, including when the
  // window is snapped or double-clicked rather than clicked in-app.
  const sendState = () => {
    if (!win.isDestroyed()) win.webContents.send('window:state', { maximized: win.isMaximized() });
  };
  win.on('maximize', sendState);
  win.on('unmaximize', sendState);
  win.webContents.on('did-finish-load', sendState);

  // Without a menu these shortcuts would be gone entirely
  win.webContents.on('before-input-event', (event, input) => {
    if (input.type !== 'keyDown') return;
    const key = (input.key || '').toLowerCase();

    if (key === 'f12' || (input.control && input.shift && key === 'i')) {
      win.webContents.toggleDevTools();
      event.preventDefault();
    } else if (input.control && key === 'r') {
      win.webContents.reload();
      event.preventDefault();
    }
  });

  return win;
}

// Window controls, driven by the custom title bar in the renderer
ipcMain.on('window:control', (event, action) => {
  const win = BrowserWindow.fromWebContents(event.sender);
  if (!win) return;

  switch (action) {
    case 'minimize':
      win.minimize();
      break;
    case 'maximize':
      if (win.isMaximized()) win.unmaximize();
      else win.maximize();
      break;
    case 'close':
      win.close();
      break;
  }
});

// Settings changes that the main process owns. The renderer saves the config
// itself, then tells us so the OS-level bits take effect without a restart.
ipcMain.on('settings:background', (event, { closeToTray, startOnLogin }) => {
  if (typeof closeToTray === 'boolean')   setConfigValue('closeToTray', closeToTray);
  if (typeof startOnLogin === 'boolean') {
    setConfigValue('startOnLogin', startOnLogin);
    applyLoginItemSetting(startOnLogin);
  }
});

// ---------------------------------------------------------------------------
// Updates from GitHub Releases (titlebar ⟳ button). See services/updater.js.
// electron-updater is only loaded in the installed app — from source there is
// no app-update.yml and nothing to install into.
// ---------------------------------------------------------------------------
let updater = null;
function getUpdater() {
  if (updater) return updater;
  let autoUpdater = null;
  if (app.isPackaged) {
    try {
      ({ autoUpdater } = require('electron-updater'));
    } catch (err) {
      console.warn('electron-updater unavailable:', err.message);
    }
  }
  updater = createUpdater({
    autoUpdater,
    isPackaged: app.isPackaged,
    currentVersion: app.getVersion(),
    send: (status) => {
      if (mainWindow && !mainWindow.isDestroyed()) mainWindow.webContents.send('update:status', status);
    },
    // quitAndInstall closes the window; without this, close-to-tray would
    // just hide it and the installer would never get to run.
    beforeRestart: () => { isQuitting = true; },
  });
  return updater;
}

ipcMain.on('update:check', () => getUpdater().check());
ipcMain.handle('app:version', () => app.getVersion());

// Second launch (desktop shortcut while the tray copy runs) — surface the
// existing window instead of starting over.
app.on('second-instance', showMainWindow);

app.whenReady().then(() => {
  console.log('App is ready, creating window...');
  initDatabase();
  mainWindow = createWindow();
  createTray();

  // Keep the OS in step with the saved preference on every launch — covers a
  // config edited by hand, and a first run where the default has never been
  // registered with Windows.
  applyLoginItemSetting(loadConfig().startOnLogin);

  // Quiet check a few seconds after launch: only lights the dot on the update
  // button, never downloads or restarts on its own.
  if (app.isPackaged) {
    setTimeout(() => getUpdater().check({ quiet: true }), 8000);
  }

  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) mainWindow = createWindow();
    else showMainWindow();
  });
});

app.on('before-quit', () => { isQuitting = true; });

app.on('window-all-closed', () => {
  // With close-to-tray on, the window is hidden rather than destroyed, so this
  // only fires on a real quit. When it's off, behave like a normal app.
  if (process.platform !== 'darwin') app.quit();
});
